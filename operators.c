#include <stdio.h>

int main(void)
{
    /* ================= 1. a+++b и b---a: разбор на токены ================= */
    printf("=== 1. Tokens: a+++b and b---a ===\n");

    /* Компилятор читает код слева направо и на каждом шаге берёт САМЫЙ ДЛИННЫЙ
     * возможный токен (правило "maximal munch").
     * В записи a+++b сначала идёт "++" (длиннее, чем "+"), затем "+".
     * Поэтому a+++b разбирается как (a++) + b, а не как a + (++b). */
    int a = 5;
    int b = 3;
    int result1 = a+++b;   /* то же самое, что a++ + b */
    printf("a+++b : a=5, b=3 -> result = %d, a after = %d, b after = %d\n",
           result1, a, b);
    /* Ожидаем: result = 5 + 3 = 8; потом a увеличивается до 6; b не меняется. */

    /* Аналогично b---a: сначала "--", затем "-", то есть (b--) - a. */
    a = 4;
    b = 10;
    int result2 = b---a;   /* то же самое, что b-- - a */
    printf("b---a : a=4, b=10 -> result = %d, a after = %d, b after = %d\n",
           result2, a, b);
    /* Ожидаем: result = 10 - 4 = 6; потом b уменьшается до 9; a не меняется. */

    /* ================= 2. Безопасные выражения: таблица ================= */
    printf("\n=== 2. Safe expressions (precedence) ===\n");

    /* Приоритет (от высокого к низкому среди используемых):
     *   *   >   +   >   <<   >   <   >   ==   >   &   >   ^   >   &&   >   ||
     * Скобки () переопределяют порядок. */
    printf("2 + 3 * 4            = %d\n", 2 + 3 * 4);       /* * раньше +  -> 14 */
    printf("(2 + 3) * 4          = %d\n", (2 + 3) * 4);     /* скобки      -> 20 */
    printf("1 << 2 + 1           = %d\n", 1 << 2 + 1);      /* + раньше << -> 1 << 3 = 8 */
    printf("(1 << 2) + 1         = %d\n", (1 << 2) + 1);    /* скобки      -> 4 + 1 = 5 */
    printf("5 < 3 == 0           = %d\n", 5 < 3 == 0);      /* < раньше == -> (5<3)==0 -> 1 */
    printf("6 & 2 == 2           = %d\n", 6 & 2 == 2);      /* == раньше & -> 6 & (2==2) = 6 & 1 = 0 */
    printf("(6 & 2) == 2         = %d\n", (6 & 2) == 2);    /* скобки      -> 2 == 2 -> 1 */
    printf("6 ^ 3                = %d\n", 6 ^ 3);           /* исключающее ИЛИ -> 5 */
    printf("1 || 0 && 0          = %d\n", 1 || 0 && 0);     /* && раньше || -> 1 || (0&&0) = 1 */
    printf("(1 || 0) && 0        = %d\n", (1 || 0) && 0);   /* скобки      -> 1 && 0 = 0 */

    /* Выражения 1 << 2 + 1 и 6 & 2 == 2 специально записаны без скобок и со скобками:
     * скобки меняют смысл (8 против 5, 0 против 1). gcc с -Wall может предупредить
     * "suggest parentheses around ..." - это нормально. */

    /* ================= 3. a = b++ + ++b : undefined behavior ================= */
    printf("\n=== 3. a = b++ + ++b  (UNDEFINED BEHAVIOR) ===\n");

    /* В этом выражении объект b изменяется ДВАЖДЫ (b++ и ++b) между двумя
     * точками следования (sequence points), и порядок вычисления операндов
     * оператора + стандартом C не определён. Результат не определён ->
     * undefined behavior. Число ниже - НЕ правильный ответ: другой компилятор,
     * другая версия или другой уровень оптимизации (-O0 / -O2) могут дать другое.
     * gcc предупредит: "operation on 'b' may be undefined" [-Wsequence-point]. */
    b = 5;
    a = b++ + ++b;
    printf("b = 5; a = b++ + ++b; -> a = %d, b = %d  (do NOT rely on this)\n", a, b);

    return 0;
}