#include "device.h"

/* ---------- 1. Глобальная переменная (external linkage) ----------
 * Объявлена вне любой функции, поэтому существует всю работу программы
 * и по умолчанию инициализируется нулём.
 * Внешняя связь означает, что линковщик "сшивает" это определение с
 * extern-объявлением из device.h в других файлах: main.c видит ЭТУ переменную.
 * Начальное значение = 0 записано явно для наглядности. */
unsigned long global_runs = 0;

/* ---------- 2. static на уровне файла (internal linkage) ----------
 * Слово static перед глобальной переменной ограничивает её видимость ТЕКУЩИМ
 * файлом: другие файлы не могут к ней обратиться, даже если напишут
 * extern unsigned long internal; - линковщик не найдёт такое имя
 * (ошибка вида "undefined reference to 'internal'").
 * Время жизни при этом всё равно вся программа. */
static unsigned long internal = 0;

/* device_tick: вызывается из main.c на каждом обработанном значении. */
void device_tick(void)
{
    /* ---------- 3. static внутри функции ----------
     * Инициализация "= 0" выполняется ОДИН раз (до начала программы),
     * а не при каждом вызове. Значение сохраняется между вызовами функции.
     * Время жизни - вся программа, а область видимости - только тело
     * device_tick (снаружи имя calls не существует).
     * Обычная локальная переменная (auto) создавалась бы заново при каждом
     * вызове, жила бы в стеке и "забывала" значение. */
    static unsigned long calls = 0;

    ++global_runs;   /* общий счётчик, виден через extern во всех файлах */
    ++internal;      /* скрытый счётчик, доступен только через device_internal_calls() */
    ++calls;           /* локальный static-счётчик; наружу не отдаётся -*/
    (void)calls;       
                       
}

/* Функция-"геттер": единственный способ узнать значение скрытой переменной internal. */
unsigned long device_internal_calls(void)
{
    return internal;
}