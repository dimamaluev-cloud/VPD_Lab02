#ifndef DEVICE_H
#define DEVICE_H

/* ---------- Объявление глобальной переменной ----------
 * Слово extern означает: "эта переменная СУЩЕСТВУЕТ, но создана в другом файле".
 * Здесь память под неё НЕ выделяется - мы лишь сообщаем компилятору её имя и тип,
 * чтобы main.c мог ею пользоваться. Реальная переменная (с выделением памяти)
 * определена в device.c. Если убрать extern, в каждом .c-файле, включившем
 * заголовок, появилась бы своя копия, и линковщик выдал бы ошибку
 * "multiple definition". */
extern unsigned long global_runs;

/* ---------- Объявления функций (прототипы) ----------
 * Прототип сообщает компилятору имя функции, типы параметров и тип результата.
 * Тело функции находится в device.c; слово extern для функций писать не нужно -
 * оно подразумевается по умолчанию. */

/* device_tick: учитывает одну "единицу работы" (увеличивает счётчики).
 * void в скобках означает "функция не принимает аргументов". */
void device_tick(void);

/* device_internal_calls: возвращает значение скрытого счётчика internal.
 * Сама переменная internal снаружи недоступна, поэтому читать её можно
 * только через такую функцию - это пример инкапсуляции в C. */
unsigned long device_internal_calls(void);

#endif /* DEVICE_H */